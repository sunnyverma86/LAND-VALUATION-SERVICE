package com.areap2.dto.excel;

public class SearchDtoRequest {

	private String districtCode;

	private String circleCode;

	private String mouzaCode;

	private String lotCode;

	private String villageCode;
	
	private String dagNumber;

	public SearchDtoRequest() {
	}

	public String getDistrictCode() {
		return districtCode;
	}

	public void setDistrictCode(String districtCode) {
		this.districtCode = districtCode;
	}

	public String getCircleCode() {
		return circleCode;
	}

	public void setCircleCode(String circleCode) {
		this.circleCode = circleCode;
	}

	public String getMouzaCode() {
		return mouzaCode;
	}

	public void setMouzaCode(String mouzaCode) {
		this.mouzaCode = mouzaCode;
	}

	public String getLotCode() {
		return lotCode;
	}

	public void setLotCode(String lotCode) {
		this.lotCode = lotCode;
	}

	public String getVillageCode() {
		return villageCode;
	}

	public void setVillageCode(String villageCode) {
		this.villageCode = villageCode;
	}

	public String getDagNumber() {
		return dagNumber;
	}

	public void setDagNumber(String dagNumber) {
		this.dagNumber = dagNumber;
	}

	

	
	
	
	
	
	

}
